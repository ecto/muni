/**
 * Build: Tokens → Typst Variables
 *
 * Generates a .typ file with #let bindings for all design tokens.
 * Import in paper/lib/template.typ: #import "../design/dist/tokens.typ": *
 */

import { palette, semantic } from "../tokens/color";
import { print } from "../tokens/typography";
import { space } from "../tokens/spacing";

function oklchToTypstRgb(oklch: string): string {
  // Typst doesn't support oklch natively, so we provide the oklch string
  // as a comment and use approximate hex values via the oklab function.
  // For now, output as color.oklch() — Typst 0.12+ supports this.
  const match = oklch.match(/oklch\(([^ ]+) ([^ ]+) ([^)]+)\)/);
  if (!match) return `rgb("#000000")`;
  const [, l, c, h] = match;
  return `oklab(${l}, ${c}, ${h})`;
}

export function buildTypst(): string {
  const lines: string[] = [];

  lines.push("// Auto-generated by @muni/design — do not edit");
  lines.push("");

  // Brand colors — use direct hex for broad Typst compatibility
  lines.push("// Brand colors");
  lines.push('#let muni-orange = rgb("#ff6600")');
  lines.push('#let muni-gray = rgb("#5C5C5C")');
  lines.push('#let muni-light-gray = rgb("#F5F5F5")');
  lines.push('#let muni-bg = rgb("#FAFAFA")');
  lines.push('#let muni-black = rgb("#000000")');
  lines.push('#let muni-white = rgb("#FFFFFF")');
  lines.push("");

  // Semantic
  lines.push("// Semantic colors");
  lines.push('#let muni-danger = rgb("#C41E3A")');
  lines.push('#let muni-note = rgb("#2563EB")');
  lines.push('#let muni-success = rgb("#22c55e")');
  lines.push('#let muni-warning = rgb("#ff6600")');
  lines.push("");

  // Typography
  lines.push("// Typography");
  lines.push(`#let muni-font-prose = "${print.proseFamily}"`);
  lines.push(`#let muni-font-mono = "${print.monoFamily}"`);
  lines.push(`#let muni-font-size = ${print.baseFontSize}`);
  lines.push(`#let muni-heading-size = ${print.headingFontSize}`);
  lines.push(`#let muni-leading = ${print.lineHeight}`);
  lines.push(`#let muni-max-width = ${print.maxWidth}`);
  lines.push("");

  // Spacing (convert px to pt: 1px ≈ 0.75pt)
  lines.push("// Spacing (selected)");
  const spacingSubset = {
    xs: space[1],
    sm: space[2],
    md: space[4],
    lg: space[6],
    xl: space[8],
    "2xl": space[12],
  };
  for (const [name, value] of Object.entries(spacingSubset)) {
    const px = parseInt(value);
    const pt = (px * 0.75).toFixed(1);
    lines.push(`#let muni-space-${name} = ${pt}pt`);
  }
  lines.push("");

  // Border / decoration
  lines.push("// Decorations");
  lines.push("#let muni-border-width = 1pt");
  lines.push("#let muni-heading-border = 3pt");
  lines.push("#let muni-code-inset = 12pt");
  lines.push("#let muni-code-radius = 0pt");
  lines.push("");

  return lines.join("\n");
}

/**
 * Build: Tokens → CSS Custom Properties
 *
 * Generates a CSS file with all design tokens as custom properties.
 * Consumed by any CSS context (depot console, design site, etc.)
 */

import { palette, semantic, theme, chart } from "../tokens/color";
import { fontFamily, fontSize, fontWeight, lineHeight, letterSpacing } from "../tokens/typography";
import { space, layout, component, maxWidth } from "../tokens/spacing";
import { duration, easing, transition } from "../tokens/motion";

function cssVar(name: string, value: string): string {
  return `  --${name}: ${value};`;
}

function flattenObject(
  obj: Record<string, unknown>,
  prefix: string,
): string[] {
  const lines: string[] = [];
  for (const [key, value] of Object.entries(obj)) {
    const name = prefix ? `${prefix}-${key}` : key;
    if (typeof value === "string") {
      lines.push(cssVar(name, value));
    } else if (typeof value === "object" && value !== null) {
      lines.push(...flattenObject(value as Record<string, unknown>, name));
    }
  }
  return lines;
}

export function buildCSS(): string {
  const lines: string[] = [];

  lines.push("/* Auto-generated by @muni/design — do not edit */");
  lines.push("");

  // Font face declarations
  lines.push("@font-face {");
  lines.push('  font-family: "Berkeley Mono";');
  lines.push("  font-weight: 400;");
  lines.push("  font-style: normal;");
  lines.push('  src: url("/fonts/BerkeleyMono-Regular.woff2") format("woff2");');
  lines.push("  font-display: swap;");
  lines.push("}");
  lines.push("");
  lines.push("@font-face {");
  lines.push('  font-family: "Berkeley Mono";');
  lines.push("  font-weight: 700;");
  lines.push("  font-style: normal;");
  lines.push('  src: url("/fonts/BerkeleyMono-Bold.woff2") format("woff2");');
  lines.push("  font-display: swap;");
  lines.push("}");
  lines.push("");

  // Root tokens (theme-independent)
  lines.push(":root {");

  // Palette
  lines.push("  /* Palette */");
  lines.push(cssVar("color-black", palette.black));
  lines.push(cssVar("color-white", palette.white));
  for (const [scale, shades] of Object.entries(palette)) {
    if (typeof shades === "object") {
      for (const [step, value] of Object.entries(shades)) {
        lines.push(cssVar(`color-${scale}-${step}`, value as string));
      }
    }
  }
  lines.push("");

  // Semantic colors
  lines.push("  /* Semantic */");
  for (const [name, value] of Object.entries(semantic)) {
    lines.push(cssVar(`color-${name}`, value));
  }
  lines.push("");

  // Chart colors
  lines.push("  /* Chart */");
  for (const [i, value] of Object.entries(chart)) {
    lines.push(cssVar(`chart-${i}`, value));
  }
  lines.push("");

  // Typography
  lines.push("  /* Typography */");
  lines.push(cssVar("font-mono", fontFamily.mono.join(", ")));
  lines.push(cssVar("font-display", fontFamily.display.join(", ")));
  for (const [name, value] of Object.entries(fontSize)) {
    lines.push(cssVar(`text-${name}`, value));
  }
  for (const [name, value] of Object.entries(fontWeight)) {
    lines.push(cssVar(`font-${name}`, value));
  }
  for (const [name, value] of Object.entries(lineHeight)) {
    lines.push(cssVar(`leading-${name}`, value));
  }
  for (const [name, value] of Object.entries(letterSpacing)) {
    lines.push(cssVar(`tracking-${name}`, value));
  }
  lines.push("");

  // Spacing
  lines.push("  /* Spacing */");
  for (const [name, value] of Object.entries(space)) {
    lines.push(cssVar(`space-${name}`, value));
  }
  lines.push("");
  lines.push("  /* Layout */");
  for (const [name, value] of Object.entries(layout)) {
    lines.push(cssVar(`layout-${name}`, value));
  }
  lines.push("");
  lines.push("  /* Component spacing */");
  for (const [name, value] of Object.entries(component)) {
    lines.push(cssVar(`component-${name}`, value));
  }
  lines.push("");
  lines.push("  /* Max widths */");
  for (const [name, value] of Object.entries(maxWidth)) {
    lines.push(cssVar(`max-w-${name}`, value));
  }
  lines.push("");

  // Motion
  lines.push("  /* Motion */");
  for (const [name, value] of Object.entries(duration)) {
    lines.push(cssVar(`duration-${name}`, value));
  }
  for (const [name, value] of Object.entries(easing)) {
    lines.push(cssVar(`ease-${name}`, value));
  }
  for (const [name, value] of Object.entries(transition)) {
    lines.push(cssVar(`transition-${name}`, value));
  }

  lines.push("}");
  lines.push("");

  // Light theme (default)
  lines.push(":root {");
  lines.push("  /* Theme: light (default) */");
  for (const [name, value] of Object.entries(theme.light)) {
    lines.push(cssVar(name, value));
  }
  lines.push("}");
  lines.push("");

  // Dark theme
  lines.push(".dark, [data-theme='dark'] {");
  lines.push("  /* Theme: dark */");
  for (const [name, value] of Object.entries(theme.dark)) {
    lines.push(cssVar(name, value));
  }
  lines.push("}");
  lines.push("");

  // Prefer dark
  lines.push("@media (prefers-color-scheme: dark) {");
  lines.push("  :root:not([data-theme='light']) {");
  for (const [name, value] of Object.entries(theme.dark)) {
    lines.push(`    --${name}: ${value};`);
  }
  lines.push("  }");
  lines.push("}");
  lines.push("");

  return lines.join("\n");
}

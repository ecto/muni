/**
 * Build: Tokens → Tailwind v4 Theme
 *
 * Generates a CSS file with @theme inline block for Tailwind v4.
 * Drop-in replacement for the manual theme in depot/console/src/index.css
 */

import { palette, theme, chart } from "../tokens/color";
import { fontFamily, fontSize, lineHeight, letterSpacing } from "../tokens/typography";
import { space, maxWidth } from "../tokens/spacing";
import { breakpoint } from "../tokens/breakpoints";

export function buildTailwind(): string {
  const lines: string[] = [];

  lines.push("/* Auto-generated by @muni/design — do not edit */");
  lines.push("/* Import this in your main CSS, then add your @theme overrides */");
  lines.push("");

  lines.push("@theme inline {");

  // Colors — expose palette as Tailwind utilities
  lines.push("  /* Colors */");
  lines.push(`  --color-black: ${palette.black};`);
  lines.push(`  --color-white: ${palette.white};`);
  for (const [scale, shades] of Object.entries(palette)) {
    if (typeof shades === "object") {
      for (const [step, value] of Object.entries(shades)) {
        lines.push(`  --color-${scale}-${step}: ${value};`);
      }
    }
  }
  lines.push("");

  // Theme colors as Tailwind utilities
  lines.push("  /* Theme (semantic) */");
  for (const [name, value] of Object.entries(theme.light)) {
    lines.push(`  --color-${name}: var(--${name}, ${value});`);
  }
  lines.push("");

  // Chart colors
  lines.push("  /* Chart */");
  for (const [i, value] of Object.entries(chart)) {
    lines.push(`  --color-chart-${i}: ${value};`);
  }
  lines.push("");

  // Typography
  lines.push("  /* Typography */");
  lines.push(`  --font-mono: ${fontFamily.mono.join(", ")};`);
  lines.push(`  --font-display: ${fontFamily.display.join(", ")};`);
  for (const [name, value] of Object.entries(fontSize)) {
    lines.push(`  --text-${name}: ${value};`);
  }
  for (const [name, value] of Object.entries(lineHeight)) {
    lines.push(`  --leading-${name}: ${value};`);
  }
  for (const [name, value] of Object.entries(letterSpacing)) {
    lines.push(`  --tracking-${name}: ${value};`);
  }
  lines.push("");

  // Spacing
  lines.push("  /* Spacing */");
  for (const [name, value] of Object.entries(space)) {
    lines.push(`  --spacing-${name}: ${value};`);
  }
  lines.push("");

  // Max widths
  lines.push("  /* Max widths */");
  for (const [name, value] of Object.entries(maxWidth)) {
    lines.push(`  --container-${name}: ${value};`);
  }
  lines.push("");

  // Breakpoints
  lines.push("  /* Breakpoints */");
  for (const [name, value] of Object.entries(breakpoint)) {
    lines.push(`  --breakpoint-${name}: ${value};`);
  }
  lines.push("");

  // Border radius — 0 everywhere (terminal aesthetic)
  lines.push("  /* Border radius */");
  lines.push("  --radius-sm: 0px;");
  lines.push("  --radius-md: 0px;");
  lines.push("  --radius-lg: 0px;");
  lines.push("  --radius-xl: 0px;");

  lines.push("}");
  lines.push("");

  return lines.join("\n");
}

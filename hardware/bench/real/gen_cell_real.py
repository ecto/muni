"""Generate cell_real.loon: the 4040 workcell with two rose fork-v5 arms hanging from the carriage.
Arm geometry/kinematics come straight from rose/arm/fork/rose_fork.py (build(), LINKS), rotated
180 deg about X (hanging) and re-expressed per link frame. Run: python3 gen_cell_real.py > cell_real.loon"""
import sys, os, math, re
FORK = __import__('os').path.join(__import__('os').environ.get('ROSE_DIR', __import__('os').path.expanduser('~/Developer/rose')), 'arm', 'fork')
sys.path.insert(0, FORK)
import rose_fork as F
from rose_arm_geom import prim_loon, sub, mul, add, unit

# ---- cell layout (mm) ----
GANTRY_Z = 920          # gantry bar bottom (bar 920..960)
RAIL_Z = 900            # rail 900..920
CAR_H = 40              # carriage plate 860..900
FOOT_Z = RAIL_Z - CAR_H  # arm base foot (hangs from carriage underside) = 860
ARM_DX = 200            # shoulders at carriage centre -/+ 200 (400 apart)
CAR_L, CAR_W = 520, 160
SH_Z = FOOT_Z - F.Z_SH * 1e3   # shoulder axis z = 640

LIM = {'J1_yaw': (-170, 170), 'J2_sho_pitch': (-150, 65), 'J4_elbow': (-170, 125),
       'J5_fore_roll': (-170, 170), 'J6_wrist_pitch': (-120, 120), 'J7_tool_roll': (-180, 180)}
hang = lambda v: (v[0], -v[1], -v[2])        # 180 deg about X: arm hangs from its base plate

def link_prims(link):
    O = F.ORIGIN[link]
    out = []
    for p in F.build():
        if p[0] != link: continue
        _, mat, o, u, v, ol, vec = p[:7]
        holes = p[7] if len(p) > 7 else []
        o2, u2, v2, w2 = hang(sub(o, O)), hang(u), hang(v), hang(vec)
        body = prim_loon((link, mat, o2, u2, v2, ol, w2))
        for h in holes:
            n = unit(w2)
            cut = prim_loon((link, mat, sub(o2, mul(n, 0.001)), u2, v2, h, add(w2, mul(n, 0.002))))
            body = '[difference %s %s]' % (cut, body)
        out.append((mat, body))
    return out

def main():
    src = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'cell_kin.loon')).read()
    head = src[:src.index('[let frame-solid')]
    frame = src[src.index('[let frame-solid'):src.index('[assembly')]
    L = [';; cell_real.loon - GENERATED by gen_cell_real.py. Workcell with two rose fork-v5 arms (RS04 x3 + RS00 x3),',
         ';; hanging from a carriage on a 1 m rail. Gantry bar z %d..%d, rail %d..%d, carriage %d..%d,' % (GANTRY_Z, GANTRY_Z + 40, RAIL_Z, RAIL_Z + 20, FOOT_Z, RAIL_Z),
         ';; arm base feet at z %d, shoulder axes at z %.0f, shoulders 400 apart (carriage centre -/+ 200).' % (FOOT_Z, SH_Z),
         ';; Joint semantics = rose_fork.py (q in deg, same signs). Because the arm hangs, positive pitch swings',
         ';; the distal link toward the CEILING; negative toward the deck. Zero pose: arm horizontal along +X.',
         ';; Fixtures unchanged from cell_kin.loon.']
    L += [l for l in head.splitlines() if l.startswith('[material')]
    L.append(F.MATERIALS.strip())
    L.append(frame.strip())
    parts, inst, joints = [], [], []
    for n in ['frame', 'deck', 'gantry', 'rail', 'carriage', 'mill', 'plate', 'reflow', 'winder', 'stock', 'finished']:
        inst.append('[instance "%s" "%s" 0 0 0]' % (n, n))
    parts += ['[part "frame" frame-solid "alu"]', '[part "deck" [cube 1420 920 20] "deck"]',
              '[part "gantry" [cube 1420 40 40] "alu"]', '[part "rail" [cube 1000 20 20] "rail"]',
              '[part "carriage" [translate %d %d %d [cube %d %d %d]] "rail"]' % (-CAR_L // 2, -CAR_W // 2, -CAR_H, CAR_L, CAR_W, CAR_H),
              '[part "mill" [cube 400 350 380] "fixture"]', '[part "plate" [cube 380 400 20] "fixture"]',
              '[part "reflow" [cube 300 300 200] "fixture"]', '[part "winder" [cube 200 200 150] "fixture"]',
              '[part "stock" [cube 300 200 120] "fixture"]', '[part "finished" [cube 200 300 120] "fixture"]']
    joints += ['[fixed-joint "deck_mount" "frame" 40 40 100 "deck" 0 0 0]',
               '[fixed-joint "gantry_mount" "frame" 40 480 %d "gantry" 0 0 0]' % GANTRY_Z,
               '[fixed-joint "rail_mount" "frame" 250 490 %d "rail" 0 0 0]' % RAIL_Z,
               '[prismatic-joint "carriage_x" 1 0 0 0 1000 "frame" 250 500 %d "carriage" 0 0 0]' % RAIL_Z]
    # one part per primitive (avoids big unions); every primitive of a link welds to the link's lead instance
    defs = {}
    for link, *_ in F.LINKS:
        defs[link] = link_prims(link)
        for k, (mat, body) in enumerate(defs[link]):
            parts.append('[part "%s_%d" %s "%s"]' % (link, k, body, mat))
    for side, dx in (('l', -ARM_DX), ('r', ARM_DX)):
        for link, joint, parent, axis, o in F.LINKS:
            lead = '%s_%s' % (side, link)
            for k in range(len(defs[link])):
                iid = lead if k == 0 else '%s_%d' % (lead, k)
                inst.append('[instance "%s" "%s_%d" 0 0 0]' % (iid, link, k))
                if k: joints.append('[fixed-joint "%s_w%d" "%s" 0 0 0 "%s" 0 0 0]' % (lead, k, lead, iid))
            if parent is None:
                joints.append('[fixed-joint "arm_%s_mount" "carriage" %d 0 %d "%s" 0 0 0]' % (side, dx, -CAR_H, lead))
                continue
            a = hang(axis); pa = hang(sub(o, F.ORIGIN[parent]))
            lo, hi = LIM[joint]
            joints.append('[revolute-joint "arm_%s_%s" %g %g %g %d %d "%s_%s" %.3f %.3f %.3f "%s" 0 0 0]' % (
                side, joint, a[0] + 0.0, a[1] + 0.0, a[2] + 0.0, lo, hi, side, parent, pa[0] * 1e3, pa[1] * 1e3, pa[2] * 1e3, lead))
    joints += ['[fixed-joint "mill_mount" "frame" 80 320 120 "mill" 0 0 0]', '[fixed-joint "plate_mount" "frame" 560 300 120 "plate" 0 0 0]',
               '[fixed-joint "reflow_mount" "frame" 1020 400 120 "reflow" 0 0 0]', '[fixed-joint "winder_mount" "frame" 1020 100 120 "winder" 0 0 0]',
               '[fixed-joint "stock_mount" "frame" 80 60 120 "stock" 0 0 0]', '[fixed-joint "finished_mount" "frame" 1240 60 120 "finished" 0 0 0]']
    L.append('[assembly\n  #[' + '\n    '.join(parts) + ']\n  #[' + '\n    '.join(inst) + ']\n  #[' + '\n    '.join(joints) + ']\n  "frame"]')
    print('\n'.join(L))

main()
